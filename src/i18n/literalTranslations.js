const LITERAL_MAP_BY_LANGUAGE = {
  pcm: PCM_LITERAL_MAP
}

const ORIGINAL_TEXT_KEY = Symbol('i18nOriginalText')
const ORIGINAL_ATTRS_KEY = Symbol('i18nOriginalAttrs')

const ATTRIBUTES_TO_TRANSLATE = ['placeholder', 'title', 'aria-label']
const hasOwn = (target, key) => Object.prototype.hasOwnProperty.call(target, key)

const escapeRegExp = (value) => String(value || '').replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const normalizeWhitespace = (value) => String(value || '').replace(/\s+/g, ' ').trim()

const toFlexibleWhitespacePattern = (source) => {
  const segments = normalizeWhitespace(source)
    .split(' ')
    .map((segment) => escapeRegExp(segment))
    .filter(Boolean)

  if (!segments.length) {
    return null
  }

  return new RegExp(segments.join('\\s+'), 'g')
}

const compileRules = (map) => {
  return Object.entries(map)
    .filter(([source, target]) => source && target && source !== target)
    .sort((a, b) => normalizeWhitespace(b[0]).length - normalizeWhitespace(a[0]).length)
    .map(([source, target]) => {
      const pattern = toFlexibleWhitespacePattern(source)
      if (!pattern) return null
      return { source, target, pattern }
    })
    .filter(Boolean)
}

const RULES_BY_LANGUAGE = Object.fromEntries(
  Object.entries(LITERAL_MAP_BY_LANGUAGE).map(([language, map]) => [language, compileRules(map)])
)

const NORMALIZED_MAP_BY_LANGUAGE = Object.fromEntries(
  Object.entries(LITERAL_MAP_BY_LANGUAGE).map(([language, map]) => {
    const normalizedMap = {}
    for (const [source, target] of Object.entries(map)) {
      const key = normalizeWhitespace(source)
      if (!key) continue
      normalizedMap[key] = target
    }
    return [language, normalizedMap]
  })
)

const NORMALIZED_TARGETS_BY_LANGUAGE = Object.fromEntries(
  Object.entries(LITERAL_MAP_BY_LANGUAGE).map(([language, map]) => {
    const targets = new Set()
    for (const target of Object.values(map)) {
      const normalizedTarget = normalizeWhitespace(target)
      if (!normalizedTarget) continue
      targets.add(normalizedTarget)
    }
    return [language, targets]
  })
)

const translateString = (value, language) => {
  const input = String(value || '')
  if (!input.trim()) return input

  const map = LITERAL_MAP_BY_LANGUAGE[language]
  const normalizedMap = NORMALIZED_MAP_BY_LANGUAGE[language]
  const normalizedTargets = NORMALIZED_TARGETS_BY_LANGUAGE[language]
  const rules = RULES_BY_LANGUAGE[language]
  if (!map || !normalizedMap || !normalizedTargets || !rules) return input

  const trimmed = input.trim()
  const normalizedTrimmed = normalizeWhitespace(trimmed)

  if (map[trimmed]) {
    const start = input.slice(0, input.indexOf(trimmed))
    const end = input.slice(input.indexOf(trimmed) + trimmed.length)
    return `${start}${map[trimmed]}${end}`
  }

  if (normalizedMap[normalizedTrimmed]) {
    const start = input.slice(0, input.indexOf(trimmed))
    const end = input.slice(input.indexOf(trimmed) + trimmed.length)
    return `${start}${normalizedMap[normalizedTrimmed]}${end}`
  }

  // If the full string already matches a translated target, avoid a second regex pass
  // that can produce duplicates like "Media Hub Hub".
  if (normalizedTargets.has(normalizedTrimmed)) {
    return input
  }

  let output = input
  for (const rule of rules) {
    output = output.replace(rule.pattern, rule.target)
  }
  return output
}

const resolveStoredOriginal = (currentValue, storedOriginal, language) => {
  const normalizedCurrent = String(currentValue || '')
  const normalizedStored = String(storedOriginal || '')
  const expectedTranslated = translateString(normalizedStored, language)

  if (normalizedCurrent === normalizedStored || normalizedCurrent === expectedTranslated) {
    return normalizedStored
  }

  return normalizedCurrent
}

const shouldSkipTextNode = (node) => {
  const parent = node.parentElement
  if (!parent) return true

  const tag = parent.tagName
  if (['SCRIPT', 'STYLE', 'NOSCRIPT', 'TEXTAREA', 'INPUT', 'OPTION'].includes(tag)) {
    return true
  }

  if (parent.closest('[data-i18n-skip="true"]')) {
    return true
  }

  return false
}

const restoreNodeText = (node) => {
  if (!hasOwn(node, ORIGINAL_TEXT_KEY)) return

  const original = String(node[ORIGINAL_TEXT_KEY] || '')
  if (node.nodeValue !== original) {
    node.nodeValue = original
  }
  delete node[ORIGINAL_TEXT_KEY]
}

const applyNodeTextTranslation = (node, language) => {
  if (shouldSkipTextNode(node)) return

  const current = String(node.nodeValue || '')
  const hadStoredOriginal = hasOwn(node, ORIGINAL_TEXT_KEY)
  const original = hadStoredOriginal
    ? resolveStoredOriginal(current, node[ORIGINAL_TEXT_KEY], language)
    : current

  const translated = translateString(original, language)

  if (translated === original) {
    if (hadStoredOriginal) {
      delete node[ORIGINAL_TEXT_KEY]
    }
    return
  }

  if (!hadStoredOriginal || node[ORIGINAL_TEXT_KEY] !== original) {
    node[ORIGINAL_TEXT_KEY] = original
  }

  if (translated !== current) {
    node.nodeValue = translated
  }
}

const restoreElementAttributes = (element) => {
  const originals = element[ORIGINAL_ATTRS_KEY]
  if (!originals || typeof originals !== 'object') return

  for (const [attr, value] of Object.entries(originals)) {
    if (element.getAttribute(attr) !== value) {
      element.setAttribute(attr, value)
    }
  }
  delete element[ORIGINAL_ATTRS_KEY]
}

const applyElementAttributeTranslation = (element, language) => {
  const originals = element[ORIGINAL_ATTRS_KEY] && typeof element[ORIGINAL_ATTRS_KEY] === 'object'
    ? element[ORIGINAL_ATTRS_KEY]
    : {}

  for (const trackedAttr of Object.keys(originals)) {
    if (!element.hasAttribute(trackedAttr)) {
      delete originals[trackedAttr]
    }
  }

  for (const attr of ATTRIBUTES_TO_TRANSLATE) {
    if (!element.hasAttribute(attr)) continue

    const current = String(element.getAttribute(attr) || '')
    const hadStoredOriginal = hasOwn(originals, attr)
    const original = hadStoredOriginal
      ? resolveStoredOriginal(current, originals[attr], language)
      : current

    const translated = translateString(original, language)

    if (translated === original) {
      if (hadStoredOriginal) {
        delete originals[attr]
      }
      continue
    }

    originals[attr] = original

    if (translated !== current) {
      element.setAttribute(attr, translated)
    }
  }

  if (Object.keys(originals).length > 0) {
    element[ORIGINAL_ATTRS_KEY] = originals
    return
  }

  if (element[ORIGINAL_ATTRS_KEY]) {
    delete element[ORIGINAL_ATTRS_KEY]
  }
}

const walkTextNodes = (root, onNode) => {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
  let node = walker.nextNode()
  while (node) {
    onNode(node)
    node = walker.nextNode()
  }
}

const walkElements = (root, onElement) => {
  if (!(root instanceof Element)) return
  onElement(root)
  const elements = root.querySelectorAll('*')
  for (const element of elements) {
    onElement(element)
  }
}

export const applyLiteralTranslations = ({ language, root }) => {
  if (typeof document === 'undefined') return

  const targetRoot = root || document.body
  if (!targetRoot) return

  if (!language || language === 'en' || !LITERAL_MAP_BY_LANGUAGE[language]) {
    walkTextNodes(targetRoot, restoreNodeText)
    walkElements(targetRoot, restoreElementAttributes)
    return
  }

  walkTextNodes(targetRoot, (node) => applyNodeTextTranslation(node, language))
  walkElements(targetRoot, (element) => applyElementAttributeTranslation(element, language))
}
